def _aln_html(s):
    aln, scheme = s["alignment"], s["scheme"]
    ml = aln.match_line(scheme)
    width = 60
    out = []
    rp, qp = aln.ref_start, aln.query_start
    for i in range(0, len(aln.aligned_ref), width):
        rs, qs, ms = aln.aligned_ref[i:i + width], aln.aligned_query[i:i + width], ml[i:i + width]
        r0, q0 = rp + 1, qp + 1
        rp += sum(1 for c in rs if c != "-")
        qp += sum(1 for c in qs if c != "-")
        def color(seq, other, mline):
            h = []
            for a, m in zip(seq, mline):
                cls = {"|": "", ":": "het", "+": "sim", ".": "mm", " ": "gap"}[m]
                h.append(f'<span class="{cls}">{escape(a)}</span>' if cls else escape(a))
            return "".join(h)
        out.append(f"Ref   {r0:>6}  {color(rs, qs, ms)}  {rp}\n"
                   f"              {escape(ms)}\n"
                   f"Query {q0:>6}  {color(qs, rs, ms)}  {qp}\n")
    return "\n".join(out)


def sources_lines(s):
    ctx = s["context"]
    on = ctx.get("_online")
    L = []
    if on:
        L.append(f"Online annotation retrieved {on.get('retrieved', '')} (cached up to 30 days):")
        L += [f"  - {x}" for x in on.get("sources", [])]
        L += [f"  - NOT AVAILABLE: {x}" for x in on.get("errors", [])]
    else:
        L.append("Online annotation: off (offline mode).")
    L += [f"  - Derived: {x}" for x in ctx.get("_derived", [])]
    kv = ctx.get("known_variants") or []
    src = {}
    for k in kv:
        tag = "ClinVar" if str(k.get("source", "")).startswith("ClinVar") else k.get("source", "user")
        src[tag] = src.get(tag, 0) + 1
    L.append("Known pathogenic variants used for PS1/PM5/hotspots: " +
             (", ".join(f"{n} from {t}" for t, n in src.items()) or "none"))
    return L


def _sources_html(s):
    return "<ul class='small'>" + "".join(f"<li>{escape(x.strip(' -'))}</li>" for x in sources_lines(s)) + "</ul>"


def _family_section(c):
    f = c.get("family")
    if not f:
        return ""
    h = (f"<h3>Family analysis</h3><p class='small muted'>Family {escape(f['family'])} - this patient: "
         f"{escape(f['relationship'] or 'member')}, {escape(f['affected'] or 'unknown')}; proband {escape(f['proband'] or '-')}. "
         "Pedigree and segregation table: see cohort_summary.html.</p><ul>"
         + "".join(f"<li>{escape(x)}</li>" for x in f["findings"]) + "</ul>")
    for cp in f.get("couples", []):
        h += f"<p><b>Couple {escape(cp['label'])}</b></p><ul>" + "".join(
            f"<li><b>{escape(r['risk'])}</b> - {escape(r['text'])}</li>" for r in cp["risks"]) + "</ul>"
    return h


def _basis_tag(v):
    if v.get("classification_basis", "ACMG").startswith("ACMG"):
        if v.get("clinvar_classification"):
            return (f"<br><span class='small muted'>ClinVar: {escape(v['clinvar_classification'])} "
                    f"{'&#9733;' * (v.get('clinvar_stars') or 0)}</span>")
        return ""
    if v.get("classification_basis", "").startswith("Known-variant"):
        src = "from your known-variant list"
    else:
        st = v.get('clinvar_stars') or 0
        src = f"from ClinVar {'&#9733;' * st or '0&#9733;'}{' (limited review)' if st < 2 else ''}"
    return (f"<br><span class='small muted'>{src}; ACMG auto: {escape(v.get('acmg_classification', ''))}</span>")


def _badge(cls, extra=""):
    col = ACMG_COLORS.get(cls, "#999")
    return f'<span class="badge" style="background:{col}">{escape(cls)}{escape(extra)}</span>'


def _genotype_box(c):
    gt = c.get("genotype")
    if not gt:
        return ""
    ph = (f", in {gt['phase']}" + (f" ({gt['phase_how']})" if gt.get("phase_how") else "")
          if gt.get("phase") in ("trans", "cis") else "")
    alle = "<br>".join(f"{escape(x['name'])} <span class='muted'>({escape(x['type'])}, "
                       f"{escape(x['classification'])})</span>" for x in gt["variants"])
    return (f"<div style='grid-column:1/-1'><span class='muted'>Genotype</span><b>{escape(gt['genotype'] + ph)}</b>"
            f"<span class='muted'>Allele types: {escape(gt['allele_types'])}</span><br>{alle}</div>")


