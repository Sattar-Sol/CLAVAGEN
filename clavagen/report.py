def _safe(s):
    return re.sub(r"[^\w.\-]+", "_", s)


def write_all(results, outdir, formats=("tsv", "vcf", "json", "md", "html", "svg", "aln")):
    os.makedirs(outdir, exist_ok=True)
    written = []
    for s in results["samples"]:
        s["svg"] = variant_map_svg(s)
        base = _safe(f"{s['query'].id}__vs__{s['reference'].id}")
        if "svg" in formats:
            p = os.path.join(outdir, f"{base}_map.svg")
            with open(p, "w") as fh:
                fh.write(s["svg"])
            written.append(p)
            png = svg_to_png(p)
            if png:
                written.append(png)
            for v in s["variants"]:
                if v.get("trace_svg"):
                    tp = os.path.join(outdir, f"{base}_{v['id']}_trace.svg")
                    with open(tp, "w") as fh:
                        fh.write(v["trace_svg"])
                    v["trace_file"] = os.path.basename(tp)
                    written.append(tp)
                    pp = svg_to_png(tp)
                    if pp:
                        written.append(pp)
        if "aln" in formats:
            p = os.path.join(outdir, f"{base}_alignment.txt")
            with open(p, "w") as fh:
                fh.write(s["alignment"].format_text(s["scheme"]))
            written.append(p)
    if "tsv" in formats:
        written.append(write_tsv(results, os.path.join(outdir, "variants.tsv")))
    if "vcf" in formats and any(s["mode"] == "dna" for s in results["samples"]):
        written.append(write_vcf(results, os.path.join(outdir, "variants.vcf")))
    if "json" in formats:
        written.append(write_json(results, os.path.join(outdir, "clinical_summary.json")))
    if "md" in formats:
        written.append(write_markdown(results, os.path.join(outdir, "clinical_summary.md")))
    if "html" in formats:
        written.append(write_html(results, os.path.join(outdir, "report.html")))
    return written


def svg_to_png(svg_path):
    """Convert SVG to PNG if cairosvg or rsvg-convert is available (the app window
    always creates PNGs itself). Returns the PNG path or None."""
    png = svg_path[:-4] + ".png"
    try:
        import cairosvg
        cairosvg.svg2png(url=svg_path, write_to=png, scale=2)
        return png
    except Exception:
        pass
    import shutil
    import subprocess
    exe = shutil.which("rsvg-convert")
    if exe:
        try:
            subprocess.run([exe, "-z", "2", svg_path, "-o", png], check=True, capture_output=True, timeout=60)
            return png
        except Exception:
            return None
    return None


def _all_variants(results):
    for s in results["samples"]:
        for v in s["variants"]:
            yield s, v


def write_tsv(results, path):
    with open(path, "w", newline="") as fh:
        w = csv.writer(fh, delimiter="\t")
        w.writerow(TSV_COLS)
        for _, v in _all_variants(results):
            row = []
            for c in TSV_COLS:
                x = v.get(c, "")
                if isinstance(x, list):
                    x = ";".join(map(str, x))
                row.append("" if x is None else x)
            w.writerow(row)
    return path


def write_vcf(results, path):
    meta = results["meta"]
    lines = ["##fileformat=VCFv4.2", f"##source=CLAVAGEN_v{meta['version']}", f"##fileDate={meta['run_date'][:10].replace('-', '')}",
             '##INFO=<ID=GENE,Number=1,Type=String,Description="Gene symbol">',
             '##INFO=<ID=HGVSC,Number=1,Type=String,Description="HGVS coding notation">',
             '##INFO=<ID=HGVSP,Number=1,Type=String,Description="HGVS protein notation">',
             '##INFO=<ID=CSQ,Number=1,Type=String,Description="Sequence Ontology consequence">',
             '##INFO=<ID=ACMG,Number=1,Type=String,Description="ACMG/AMP classification">',
             '##INFO=<ID=ACMG_CRIT,Number=.,Type=String,Description="ACMG criteria met">',
             '##INFO=<ID=ACMG_PTS,Number=1,Type=Integer,Description="Bayesian points (Tavtigian 2020)">',
             '##FORMAT=<ID=GT,Number=1,Type=String,Description="Genotype (1/1 = apparent homozygous from consensus)">']
    contigs = {}
    recs = []
    samples = sorted({s["query"].id for s in results["samples"] if s["mode"] == "dna"})
    for s, v in _all_variants(results):
        if s["mode"] != "dna":
            continue
        ctx = s["context"]
        chrom = ctx.get("chrom") or s["reference"].id
        off = int(ctx.get("genomic_offset") or 0)
        contigs[chrom] = len(s["ref_seq"]) + off
        seq = s["ref_seq"]
        st, en = v["ref_pos"] - 1, v["ref_end"]
        if v["kind"] in ("SNV", "MNV"):
            pos, ref, alt = st + 1, v["ref_allele"], v["alt_allele"]
        else:
            if v["kind"] in ("insertion", "duplication"):
                en = st
            if st > 0:
                pos, ref, alt = st, seq[st - 1] + seq[st:en], seq[st - 1] + v["alt_allele"]
            else:
                pos, ref, alt = 1, seq[st:en] + seq[en], v["alt_allele"] + seq[en]
        gt = "0/1" if v["zygosity"] == "heterozygous" else "1/1"
        info = (f"GENE={v['gene'] or '.'};HGVSC={v['hgvs_c_full'] or '.'};HGVSP={v['hgvs_p'] or '.'};"
                f"CSQ={v['consequence']};ACMG={v['classification'].replace(' ', '_')};"
                f"ACMG_CRIT={','.join(v['criteria_met']) or '.'};ACMG_PTS={v['points']}")
        gts = ["./." if q != s["query"].id else gt for q in samples]
        recs.append((chrom, pos + off, v["id"], ref, alt, ".", "PASS", info, "GT", *gts))
    for c, l in contigs.items():
        lines.append(f"##contig=<ID={c},length={l}>")
    lines.append("\t".join(["#CHROM", "POS", "ID", "REF", "ALT", "QUAL", "FILTER", "INFO", "FORMAT", *samples]))
    for r in sorted(recs, key=lambda x: (x[0], x[1])):
        lines.append("\t".join(map(str, r)))
    with open(path, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    return path


def _sample_json(s):
    return {
        "query": {"id": s["query"].id, "type": s["query"].mol_type, "length": len(s["query"]), "sha256": s["query"].sha256},
        "reference": {"id": s["reference"].id, "type": s["reference"].mol_type, "length": len(s["reference"])},
        "gene": s["context"].get("gene"), "transcript": s["context"].get("transcript"),
        "mode": s["mode"], "qc": s["qc"], "clinical_summary": s["clinical"],
        "annotation_sources": sources_lines(s),
        "alignment": {"score": s["alignment"].score, "ref_span": [s["alignment"].ref_start + 1, s["alignment"].ref_end],
                      "query_span": [s["alignment"].query_start + 1, s["alignment"].query_end],
                      "backend": s["alignment"].backend, **s["alignment"].stats},
        "variants": [{k: v for k, v in var.items() if k not in ("junctions_c", "trace_svg")} for var in s["variants"]],
    }


def write_json(results, path):
    data = {"meta": results["meta"], "samples": [_sample_json(s) for s in results["samples"]],
            "disclaimer": DISCLAIMER}
    with open(path, "w") as fh:
        json.dump(data, fh, indent=2, default=str)
    return path


def write_markdown(results, path):
    m = results["meta"]
    L = ["# Clinical variant summary", "",
         f"*CLAVAGEN v{m['version']} - run {m['run_date']}*", ""]
    pt = m.get("patient") or {}
    if pt:
        L.append("**Patient:** " + ", ".join(f"{k}: {v}" for k, v in pt.items() if v))
    if m.get("phenotypes"):
        L.append("**Indication / phenotype:** " + "; ".join(m["phenotypes"]))
    L.append("")
    L.append("## Overview")
    L.append("")
    L.append("| Query | Gene | Variant (c.) | Protein | Type | Zygosity | Class | Points | Criteria |")
    L.append("|---|---|---|---|---|---|---|---|---|")
    for s, v in _all_variants(results):
        L.append(f"| {s['query'].id} | {v['gene'] or '-'} | {v['hgvs_c_full'] or '-'} | {v['hgvs_p'] or '-'} | "
                 f"{v['consequence_label']} | {v['zygosity_short']} | **{v['classification']}**"
                 f"{'' if v.get('classification_basis', 'ACMG').startswith('ACMG') else ' (ClinVar ' + str(v.get('clinvar_stars')) + '★; ACMG auto: ' + v.get('acmg_classification', '') + ')'}"
                 f"{' (' + v['vus_subtier'] + ')' if v['vus_subtier'] else ''} | {v['points']} | "
                 f"{', '.join(v['criteria_met']) or '-'} |")
    if not any(True for _ in _all_variants(results)):
        L.append("| - | - | No variants detected | | | | | | |")
    for s in results["samples"]:
        c = s["clinical"]
        L += ["", f"## {s['query'].id} vs {s['reference'].id}", ""]
        st = s["alignment"].stats
        L.append(f"- **Gene:** {c['gene']}  |  **Inheritance:** {c['inheritance']}"
                 f"{'  |  ACMG SF gene' if c['acmg_sf_gene'] else ''}")
        L.append(f"- **Result:** {c['status']} (highest class: {c['highest_class']})")
        gt = c.get("genotype")
        if gt:
            L.append(f"- **Genotype ({gt['gene']}):** {gt['genotype']}"
                     + (f", in {gt['phase']}" + (f" ({gt['phase_how']})" if gt.get('phase_how') else "")
                        if gt.get('phase') in ('trans', 'cis') else "")
                     + f"  |  allele types: {gt['allele_types']}  |  "
                     + "; ".join(f"{x['name']} = {x['type']}, {x['classification']}" for x in gt["variants"]))
        L.append(f"- **Alignment:** identity {st['identity_pct']}%, ref span {s['alignment'].ref_start + 1}-"
                 f"{s['alignment'].ref_end}, gaps {st['gaps']}"
                 + (f", CDS coverage {s['qc'].get('cds_coverage_pct')}%" if s['qc'].get('cds_coverage_pct') is not None else ""))
        for w in s["qc"].get("warnings", []) + s["qc"].get("notes", []):
            L.append(f"- QC: {w}")
        L += ["", "### Interpretation", ""] + [f"- {x}" for x in c["interpretation"]]
        if c["diseases"]:
            L += ["", "### Associated condition(s)", ""]
            for d in c["diseases"]:
                L.append(f"- **{d['name']}** ({d.get('inheritance', '')}{', MIM ' + d['mim'] if d.get('mim') else ''}): "
                         f"{d.get('summary', '')}")
                if d.get("features"):
                    L.append(f"  - Key features: {', '.join(d['features'])}")
        for v in s["variants"]:
            L += ["", f"### {v['id']}: {v['hgvs_c_full'] or ''} {v['hgvs_p'] or ''}".rstrip(), ""]
            L.append(v["interpretation"])
            L.append("")
            L.append("| Criterion | Status | Strength | Source | Rationale |")
            L.append("|---|---|---|---|---|")
            for cr in v["criteria"]:
                L.append(f"| {cr['label']} | {cr['status']} | {cr['strength'] or '-'} | {cr['source']} | "
                         f"{cr['rationale'].replace('|', '/')} |")
        L += ["", "### Recommendations", ""] + [f"- {r}" for r in c["recommendations"]]
        f = c.get("family")
        if f:
            L += ["", "### Family analysis", "", f"Family {f['family']}; this patient: {f['relationship'] or 'member'}, "
                  f"{f['affected'] or 'unknown'}; proband {f['proband']}.", ""] + [f"- {x}" for x in f["findings"]]
            for cp in f.get("couples", []):
                L += ["", f"**Couple {cp['label']}**", ""] + [f"- **{r['risk']}** - {r['text']}" for r in cp["risks"]]
        L += ["", "### Annotation sources", ""] + [f"- {x.strip(' -')}" for x in sources_lines(s)]
    L += ["", "---", "", f"*{DISCLAIMER}*", ""]
    with open(path, "w") as fh:
        fh.write("\n".join(L))
    return path


